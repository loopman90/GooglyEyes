import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function assertString(value, fallback) {
  return typeof value === "string" && value.length ? value : fallback;
}

function eyeWindowsBySide(windows) {
  const left = windows.find((window) => window.side === "left");
  const right = windows.find((window) => window.side === "right");
  if (!left || !right) throw new Error("skin.json must include left and right eye windows");
  return { left, right };
}

const manifest = readJson(join(root, "assets", "skins.json"));
const skins = manifest.skins.map((id) => {
  const file = join(root, "assets", "skins", id, "skin.json");
  if (!existsSync(file)) throw new Error(`Missing skin metadata: ${file}`);
  const skin = readJson(file);
  const defaults = skin.defaults ?? {};
  return {
    id,
    name: assertString(skin.name, id),
    eyeLayout: skin.eyeLayout === "single" ? "single" : "dual",
    flavor: assertString(skin.flavor ?? skin.description, id),
    iris: assertString(defaults.irisColor, "#42d9ff"),
    pupil: assertString(defaults.pupilColor, "#07111b"),
    eyeWhite: assertString(defaults.eyeWhiteColor, "#f4eadc"),
    outline: assertString(defaults.eyelidColor, "#2a2d30"),
    accent: assertString(defaults.eyelidShadowColor ?? defaults.accentColor, "#ffcc33"),
    irisSize: Number(defaults.irisSize ?? 34),
    pupilSize: Number(defaults.pupilSize ?? 30),
    eyeStyle: {
      slotRadius: assertString(skin.eyeStyle?.slotRadius, "999px"),
      lidLeft: assertString(skin.eyeStyle?.lidLeft, "-28%"),
      lidWidth: assertString(skin.eyeStyle?.lidWidth, "156%"),
      lidHeight: assertString(skin.eyeStyle?.lidHeight, "112%"),
      lidUpperRadius: assertString(skin.eyeStyle?.lidUpperRadius, "0 0 55% 55%"),
      lidLowerRadius: assertString(skin.eyeStyle?.lidLowerRadius, "55% 55% 0 0")
    },
    supportsColorOverrides: true,
    assets: {
      leftBase: `assets/skins/${id}/${assertString(skin.assets?.leftBase, "eyes/left-base.png")}`,
      rightBase: `assets/skins/${id}/${assertString(skin.assets?.rightBase, "eyes/right-base.png")}`,
      thumbnail: `assets/skins/${id}/${assertString(skin.thumbnail, "thumbnail.png")}`,
      mask: `assets/skins/${id}/${assertString(skin.mask, "masks/tab-panel.png")}`
    },
    eyeWindows: eyeWindowsBySide(skin.eyeWindows ?? []),
    ambientReactions: Array.isArray(skin.ambientReactions) && skin.ambientReactions.length
      ? skin.ambientReactions
      : ["blink", "look-left", "look-right", "idle-long"]
  };
});

const generated = `// Generated by scripts/generate-skin-data.mjs. Edit assets/skins/*/skin.json instead.
export const GENERATED_SKINS = ${JSON.stringify(skins, null, 2)} as const;

export const GENERATED_LAYERED_SKINS = new Set(${JSON.stringify(manifest.layeredSkins ?? [])});

export const GENERATED_SKIN_EYE_WINDOWS = Object.fromEntries(
  GENERATED_SKINS.map((skin) => [skin.id, skin.eyeWindows])
);

export const GENERATED_SKIN_AMBIENT_REACTIONS = Object.fromEntries(
  GENERATED_SKINS.map((skin) => [skin.id, skin.ambientReactions])
);
`;

writeFileSync(join(root, "generated-skins.ts"), generated);
console.log(`Generated generated-skins.ts from ${skins.length} active skins.`);
